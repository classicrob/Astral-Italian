#!/usr/bin/env python3
"""Generate explicit null-render entry points from the hooked public GX headers."""
import argparse
from pathlib import Path
import re
import subprocess


def declarations(root):
    found = {}
    for path in sorted(root.glob("*.h")):
        pre = subprocess.run(["unifdef", "-DGALAXY_NATIVE", "-U__MWERKS__"], input=path.read_text() + "\n", capture_output=True, text=True)
        if pre.returncode not in (0, 1):
            raise ValueError(pre.stderr)
        text = re.sub(r"/\*.*?\*/|//[^\n]*", "", pre.stdout, flags=re.S)
        for match in re.finditer(r"^\s*(?:extern\s+)?([\w]+(?:\s*\*)?)\s+((?:__)?GX\w+)\s*\(([^;{}]*)\)\s*(?:NO_INLINE)?\s*;", text, re.M):
            result, name, arguments = match.groups()
            found[name] = (result, " ".join(arguments.split()))
    return found


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("headers", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--manual", type=Path, required=True)
    args = parser.parse_args()
    implemented = set(re.findall(r"\b((?:__)?GX\w+)\s*\(", args.manual.read_text()))
    lines = ["// Generated by gen_gx_noops.py; rendering state is intentionally discarded."]
    for name, (result, arguments) in declarations(args.headers).items():
        if name in implemented:
            continue
        params = [] if arguments in ("", "void") else arguments.split(",")
        if result == "void" and not name.startswith(("GXGet", "GXRead", "GXPeek")):
            body = "++gCalls;"
        else:
            body = f'unsupported("{name}");'
        lines.append(f'{result} {name}({", ".join(params)}) {{ {body} }}')
    args.output.write_text("\n".join(lines) + "\n")
    print(f"generated {len(lines) - 1} null GX entry points")


if __name__ == "__main__":
    main()

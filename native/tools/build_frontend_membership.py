#!/usr/bin/env python3
"""Reproduce frontend membership from the retained warm title pair, never global rank.

--recording-dir verifies raw logs against PROVENANCE.json and extracts compact
source evidence. The checked-in evidence permits deterministic regeneration on a
server without the raw recording tree; --check additionally checks header bytes.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sqlite3

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'native/data/frontend-membership-source.json'
HEADER = ROOT / 'native/gx/frontend_membership.hpp'
EVENT = re.compile(r'\[gx stage config\] stage=(Unknown|FileSelect) config=([0-9a-f]{16})\b')

def sha(data): return hashlib.sha256(data).hexdigest()

def extract(recording):
    provenance_bytes = (recording / 'PROVENANCE.json').read_bytes()
    provenance = json.loads(provenance_bytes)
    arms = {a['name']: a for a in provenance['stage_results'][0]['arms']}
    result = {'version': 1, 'recording_source': provenance['recording_build_metadata']['source'],
              'recording_provenance_sha256': sha(provenance_bytes), 'arms': []}
    for name in ('warm-1', 'warm-2'):
        raw = (recording / 'FileSelect' / name / 'app.log').read_bytes()
        if sha(raw) != arms[name]['app_log_sha256']: raise ValueError('raw log provenance mismatch')
        text = raw.decode(errors='replace')
        if text.count('Petari: quitting') != 1: raise ValueError('missing/ambiguous native quit')
        # Preserve native log event order, not an invented cross-thread packet.
        pre, post = text.split('Petari: quitting')
        result['arms'].append({'name': name, 'app_log_sha256': sha(raw), 'quit_markers': 1,
                              'events_before_quit': [list(x) for x in EVENT.findall(pre)],
                              'events_after_quit': [list(x) for x in EVENT.findall(post)]})
    return result

def membership(source):
    if source['version'] != 1 or len(source['arms']) != 2: raise ValueError('source format')
    sets, excluded = [], []
    for arm in source['arms']:
        if arm['quit_markers'] != 1: raise ValueError('missing/ambiguous quit')
        stages = {s: set() for s in ('Unknown', 'FileSelect')}
        for stage, key in arm['events_before_quit']:
            if stage not in stages or not re.fullmatch('[0-9a-f]{16}', key): raise ValueError('invalid event')
            stages[stage].add(key)
        sets.append(stages)
        excluded.append(set(map(tuple, arm['events_after_quit'])))
    if sets[0] != sets[1] or excluded[0] != excluded[1]: raise ValueError('warm membership disagrees')
    if not all(sets[0].values()): raise ValueError('empty frontend source')
    return sets[0]

def render(source, seed_dir):
    stages = membership(source)
    with sqlite3.connect(f'file:{seed_dir / "__global__.db"}?mode=ro', uri=True) as db:
        rows = {f'{h & ((1<<64)-1):016x}': (version, size, bytes(config)) for h, version, size, config in
                db.execute('SELECT hash,config_version,config_size,config FROM pipeline_cache WHERE type=1')}
    selected, uncovered = [], []
    for key in sorted(set.union(*stages.values())):
        if key not in rows: uncovered.append(key); continue
        version, size, data = rows[key]
        if version != 13 or size != len(data) or size != 2772: raise ValueError('invalid global row')
        selected.append((key, sha(data)))
    lines = ['// Generated by native/tools/build_frontend_membership.py; do not edit.', '#pragma once',
             '#include <cstdint>', '#include <array>', 'namespace PetariFrontendMembership {',
             f'inline constexpr unsigned kVersion = 1;',
             f'inline constexpr const char* kEvidenceSha256 = "{sha((json.dumps(source, indent=2, sort_keys=True)+chr(10)).encode())}";',
             f'inline constexpr std::array<std::uint64_t, {len(selected)}> kGlobalHashes{{{{']
    lines += [f'    0x{key}ULL, // global config SHA256 {digest}' for key, digest in selected]
    lines += ['}};', f'inline constexpr std::array<std::uint64_t, {len(uncovered)}> kUncovered{{{{']
    lines += [f'    0x{key}ULL,' for key in uncovered]
    lines += ['}};', '} // namespace PetariFrontendMembership', '']
    return '\n'.join(lines)

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--recording-dir', type=Path)
    p.add_argument('--seed-dir', type=Path, required=True)
    p.add_argument('--source', type=Path, default=SOURCE)
    p.add_argument('--header', type=Path, default=HEADER)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    source = extract(a.recording_dir) if a.recording_dir else json.loads(a.source.read_text())
    encoded = json.dumps(source, indent=2, sort_keys=True) + '\n'
    header = render(source, a.seed_dir)
    if a.check:
        if encoded != a.source.read_text() or header != a.header.read_text(): raise ValueError('generated bytes differ')
    else:
        a.source.write_text(encoded); a.header.write_text(header)
    print('frontend membership: exact warm pair / existing global rows / generated bytes OK')

if __name__ == '__main__': main()

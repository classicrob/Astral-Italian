JAISoundID AudTalkSoundData::getSoundIDFromTalkSoundNo(u8 soundNo) {
    if ((s32)soundNo >= ARRAY_SIZE(::cTalkSoundList)) {
        return -1;
    }
    return ::cTalkSoundList[soundNo];
}
